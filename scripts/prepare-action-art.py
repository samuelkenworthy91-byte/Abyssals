"""Normalize approved generated animation sheets to a crisp 64-pixel cell grid."""
from PIL import Image,ImageDraw,ImageFont
from pathlib import Path
import json,hashlib,re,argparse,subprocess
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--sources',required=True,help='JSON of approved source PNG paths, names and action briefs');args=parser.parse_args()
paths=json.loads(Path(args.sources).read_text())
moves=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {DATA} from './dist/data.js'; console.log(JSON.stringify(DATA.moves))"],cwd=root,text=True))
ids={m['name']:m['id'] for m in moves}
ids.update({'Stillwater · Threefold Answer':790,'Berry Pantry · Recovery':791,'Draining Roots · Siphon':792,'Brine Veil · Riposte':793})
runtime=root/'dist/assets/vfx/action';runtime.mkdir(parents=True,exist_ok=True)
manifest={};provenance=[];tiles=[]
for item in paths:
 name=item['name'];id=ids[name];key=re.sub('[^a-z0-9]+','-',name.lower()).strip('-')
 im=Image.open(item['path']).convert('RGBA')
 assert .75<im.width/im.height<1.34,(name,im.size)
 assert im.getextrema()[3][0]==0,(name,'missing transparency')
 atlas=Image.new('RGBA',(256,256));cellX=im.width/4;cellY=im.height/4
 coverage=[]
 for frame in range(16):
  box=(round(frame%4*cellX),round(frame//4*cellY),round((frame%4+1)*cellX),round((frame//4+1)*cellY))
  crop=im.crop(box).resize((64,64),Image.Resampling.NEAREST)
  # Discard barely visible alpha fringes; keep the opaque shaded artwork intact.
  crop.putalpha(crop.getchannel('A').point(lambda a:255 if a>=96 else 0))
  atlas.paste(crop,((frame%4)*64,(frame//4)*64));coverage.append(bool(crop.getbbox()))
 assert sum(coverage)>=8,(name,'too few visible frames')
 dest=runtime/(str(id)+'-'+key+'.png');temp=dest.with_suffix(".verified.png");atlas.save(temp,optimize=True);temp.replace(dest)
 duration=2000 if id==790 else 1600 if id>=790 else 1500 if next((m.get('category')=='STATUS' for m in moves if m['id']==id),False) else 1350
 manifest[str(id)]={'id':id,'key':key,'name':name,'src':dest.relative_to(root/'dist').as_posix(),'frames':16,'logicalCell':64,'duration':duration,'impact':7/16 if id==790 else .5,'beats':[1/16,4/16,7/16] if id==790 else [.5],'orchard':742<=id<=784 or 790<=id<=793,'sequence':item['brief'],'individual':True}
 provenance.append({'id':id,'name':name,'brief':item['brief'],'generator':'built-in image_gen','sourceSha256':hashlib.sha256(Path(item['path']).read_bytes()).hexdigest(),'runtimeSha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'logicalCell':64,'frameCount':16,'visibleFrames':sum(coverage)})
 tile=Image.new('RGB',(250,190),'#25302f');d=ImageDraw.Draw(tile);d.text((7,6),str(id)+' '+name[:30],fill='#f0eee3')
 for j,f in enumerate([5,9,11]):
  crop=atlas.crop(((f%4)*64,(f//4)*64,(f%4+1)*64,(f//4+1)*64)).resize((78,78),Image.Resampling.NEAREST);tile.paste(crop,(5+j*82,40),crop)
 d.text((7,132),'Action / resolution / aftermath',fill='#a7c1b3');tiles.append(tile)
(root/'dist/action-vfx-data.js').write_text('// Authored, stable-ID action animation assets. Generated by prepare-action-art.py.\nexport const ACTION_ART='+json.dumps(manifest,ensure_ascii=False,separators=(',',':'))+';\n')
(root/'art-library/action-vfx/provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2))
for start in range(0,len(tiles),24):
 chunk=tiles[start:start+24];sheet=Image.new('RGB',(1000,((len(chunk)+3)//4)*190),'#25302f')
 for i,t in enumerate(chunk):sheet.paste(t,((i%4)*250,(i//4)*190))
 sheet.save(root/'build/qa'/('action-art-review-'+str(start//24+1)+'.png'))
print('Prepared',len(manifest),'independent 16-frame pixel animations;',sum(p.stat().st_size for p in runtime.glob('*.png')),'runtime bytes.')
# Existing atlas art is sampled to its logical grid rather than blurred by CSS.
# Preserve the layout and aspect ratio; all original cell coordinates still work.
for p in (root/'dist/assets/vfx').glob('*.webp'):
 if p.name.startswith(('moves-','signature-')) and '.normalized' not in p.name:
  im=Image.open(p).convert('RGBA');size=(256,384) if p.name.startswith('moves-') else (192,256)
  if im.size==size:continue
  im=im.resize(size,Image.Resampling.NEAREST);temp=p.with_suffix('.normalized.webp');im.save(temp,format='WEBP',lossless=True,method=4);temp.replace(p)
print('Existing atlases use a crisp 64-pixel cell grid.')
