import assert from 'node:assert/strict';
import {exchangePurchaseQuote,purchase} from '../dist/marasen-activities-ui.js';
import fs from 'node:fs';
import {DATA} from '../dist/data.js';
import {ensureFieldJournal,recordFieldSighting,recordFieldBattle,fieldJournalStatus,fieldJournalCounts,fieldJournalLiving,fieldJournalLosses,fieldJournalGrowth,fieldJournalHabitats,fieldJournalRumours,fieldJournalAvailability,fieldJournalMoves,fieldJournalEvolutions,fieldJournalAllSpecies} from '../dist/field-journal.js';
const pick=id=>DATA.species.find(s=>s.id===id);
const state={party:[],reserve:[],dead:[],starter:null};
assert.equal(fieldJournalStatus(state,'001'),'unknown');
assert(recordFieldSighting(state,'001','march'));
assert.equal(fieldJournalStatus(state,'001'),'seen');
assert.equal(state.fieldJournal.seen['001'].room,'march');
recordFieldSighting(state,'001','tunnels');
assert.equal(state.fieldJournal.seen['001'].room,'march','keep first sighting');
const hidden='003';
recordFieldBattle(state,{kind:'wild',trainer:{},enemies:[{species:pick('002')},{species:pick(hidden)}]},'tunnels');
assert.equal(fieldJournalStatus(state,'002'),'seen');
assert.equal(fieldJournalStatus(state,hidden),'unknown','trainer reserve is not revealed');
recordFieldBattle(state,{kind:'wild',relicDouble:true,activeEnemyIndices:[0,2],enemies:[{species:pick('004')},{species:pick('005')},{species:pick('006')}]},'march');
assert.equal(fieldJournalStatus(state,'004'),'seen');
assert.equal(fieldJournalStatus(state,'005'),'unknown');
assert.equal(fieldJournalStatus(state,'006'),'seen');
const u={uid:'test-1',species:pick('002'),level:40,hp:50,dead:false,evolutionHistory:[{from:'001',to:'002'}]};
state.party.push(u);
ensureFieldJournal(state);
assert.equal(fieldJournalStatus(state,'002'),'living');
assert.equal(fieldJournalStatus(state,'001'),'owned','remember caught pre-evolution species');
assert.equal(fieldJournalLiving(state,'002').length,1);
state.party=[];state.dead=[{...u,hp:0,dead:true}];
assert.equal(fieldJournalStatus(state,'002'),'owned','permadeath preserves catch');
assert.equal(fieldJournalLosses(state,'002'),1);
state.dead=[];assert.equal(fieldJournalStatus(state,'002'),'owned','even rehoming preserves catch');
assert.equal(fieldJournalStatus(state,'001'),'owned');
assert(fieldJournalCounts(state).seen>=4);
assert(fieldJournalAllSpecies().length===DATA.species.length);
assert(fieldJournalGrowth(pick('002')).original.hp>0);
assert(Array.isArray(fieldJournalMoves('002')));
assert(fieldJournalEvolutions('001').some(e=>e.from.id==='001'));
assert(fieldJournalHabitats('010').length>0,'first road species should have a real habitat');
assert(fieldJournalHabitats('364').some(h=>h.area.includes('Sunken Fort')));
assert.match(fieldJournalRumours('364'),/near Dorelem/);
assert.equal(fieldJournalAvailability('364').kind,'wild');
assert.match(fieldJournalRumours('010'),/near Civeton/);
assert(!fieldJournalRumours('010').includes('Civeton March'));
assert(fs.readFileSync('dist/field-journal-ui.js','utf8').includes('journalTitle()'));
assert(fs.readFileSync('dist/field-journal-ui.js','utf8').includes('art(species,!caught)'));
assert(fs.readFileSync('dist/exploration-world.js','utf8').includes('[[38,24],[40,24],[40,22]]'));
assert(fs.readFileSync('dist/marasen-activities-ui.js','utf8').includes('mr-shop-quantity'));
assert(fs.readFileSync('dist/app.js','utf8').includes('id="berry-qty"')&&fs.readFileSync('dist/app.js','utf8').includes('id="core-qty"'));
assert(fs.readFileSync('dist/marasen-activities-ui.js','utf8').includes('id="mr-tonic-count"'));

const shopState={money:15000,moveScrolls:{},heldItems:{},evolutionItems:{}};
const codex={kind:'codex',id:'777',price:250},quote=exchangePurchaseQuote(shopState,codex,50);
assert.equal(quote.valid,true);assert.equal(quote.total,12500);
assert(purchase(shopState,codex,50));assert.equal(shopState.money,2500);assert.equal(shopState.moveScrolls['777'],50);
assert(!exchangePurchaseQuote(shopState,codex,11).valid,'cannot buy beyond available money');
shopState.money=40000;const once={kind:'supply',id:'lifeEmbers',price:40000};
assert(exchangePurchaseQuote(shopState,once,1).valid);assert(!exchangePurchaseQuote(shopState,once,2).valid);
assert(purchase(shopState,once,1));assert(!exchangePurchaseQuote(shopState,once,1).valid,'no duplicate life ember');
const app=fs.readFileSync('dist/app.js','utf8'),html=fs.readFileSync('dist/index.html','utf8'),offline=fs.readFileSync('dist/offline-assets.js','utf8');
assert(app.includes('menu-field-journal')&&app.includes('recordFieldBattle(state,battle,room)'));
assert(!app.includes('growth-report.html')&&!app.includes('move-lab.html')&&!app.includes('follower-catalogue.html'));
for(const file of ['field-journal.js','field-journal-ui.js','field-journal.css'])assert(offline.includes('"'+file+'"'));
assert(html.includes('field-journal.css')&&html.includes('app.js?v=0.90.45'));
console.log('PASS: persistent sightings and ownership, trainer reserve secrecy, active double battles, evolution, death, habitats, growth and offline menu wiring');
